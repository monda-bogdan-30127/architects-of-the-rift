// Sursa așteptată: gol.gg (sau echivalent) filtrat pe turneu ȘI pe rol, același
// eșantion ca statistica globală (Worlds 2026). Câmpurile:
//   picks / bans            — număr de pick-uri / ban-uri pe acest rol
