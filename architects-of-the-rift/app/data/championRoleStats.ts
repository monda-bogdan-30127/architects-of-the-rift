//   presence                — număr de jocuri cu pick sau ban (≈ picks + bans)
//   prioScore               — scor de prioritate în draft (aceeași scală ca global, ~0..100)
//   wins / losses           — victorii / înfrângeri pe acest rol
//   proWinRate              — winrate pro, procent 0..100 (ex. 54)
//   kda                     — KDA mediu
//   avgBanTurn              — tura medie de ban
//   avgPickRound            — runda medie de pick (1 = primele pick-uri)
//   blindPickRate           — % din pick-uri făcute blind, fără adversar de linie vizibil (0..100)
//   averageGameTime         — durata medie a jocului, "mm:ss"
//   csPerMinute             — CS / minut
//   damagePerMinute         — damage / minut
//   goldPerMinute           — gold / minut
//   csDiffAt15 / goldDiffAt15 / xpDiffAt15 — diferența față de adversarul de linie la 15:00
//   soloqKrChallengerWinRate — winrate soloq KR Challenger, procent (ex. 52.4)

